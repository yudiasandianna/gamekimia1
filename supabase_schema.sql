-- 1. Buat tabel penampung hasil game
CREATE TABLE IF NOT EXISTS public.game_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    player1 TEXT NOT NULL,
    score1 INTEGER DEFAULT 0,
    correct1 INTEGER DEFAULT 0,
    pull1 INTEGER DEFAULT 0,
    player2 TEXT NOT NULL,
    score2 INTEGER DEFAULT 0,
    correct2 INTEGER DEFAULT 0,
    pull2 INTEGER DEFAULT 0,
    level TEXT DEFAULT 'easy',
    winner TEXT,
    reflection TEXT
);

-- 2. Aktifkan Row Level Security (RLS)
ALTER TABLE public.game_results ENABLE ROW LEVEL SECURITY;

-- 3. Beri izin kepada pemain anonim / murid (anon key) untuk menyimpan data skor
CREATE POLICY "Izinkan insert anonim untuk game kimia"
ON public.game_results
FOR INSERT
TO anon
WITH CHECK (true);

-- 4. Beri izin untuk membaca data skor
CREATE POLICY "Izinkan select anonim untuk game kimia"
ON public.game_results
FOR SELECT
TO anon
USING (true);

